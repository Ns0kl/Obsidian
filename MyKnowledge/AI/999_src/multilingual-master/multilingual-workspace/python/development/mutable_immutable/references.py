# オブジェクト
def add(x):
    print('更新前の識別値', id(x))
    x += [1]
    print('更新後の識別値', id(x))
    
a = [1]
add(a)
print('呼び出し元の識別値', id(a))
a

# 更新前の識別値 140212299280576
# 更新後の識別値 140212299280576
# 呼び出し元の識別値 140212299280576
# [1,1]