# 参照渡し

# プリミティブ
def add(x):
    print('更新前の識別値', id(x))
    x += 1
    print('更新後の識別値', id(x))
    
a = 1
add(a)
print('呼び出し元の識別値', id(a))
a

# 更新前の識別値 9788608
# 更新後の識別値 9788640
# 呼び出し元の識別値 9788608
# 1

